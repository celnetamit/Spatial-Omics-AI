/**
 * The implementation register — this lab's account of itself.
 *
 * One row per capability the handbook asks for, with what was built, what
 * produced it, where its data lives and the evidence behind it. Including the
 * rows that say a capability is deliberately absent, partial, or present in a
 * weaker form than the specification describes.
 *
 * It is shown to everyone, not only to auditors. A lab that publishes its
 * limitations only to the people auditing it is telling two different stories.
 */

export type RegisterStatus =
  /** Built as the handbook describes. */
  | 'implemented'
  /** Built, but in a weaker or narrower form than specified. */
  | 'partial'
  /** Deliberately not built in V1, with the reason. */
  | 'absent'
  /** Present as a stated engineering guardrail rather than a scientific claim. */
  | 'guardrail';

export interface RegisterEntry {
  id: string;
  /** Handbook section this answers. */
  section: string;
  capability: string;
  status: RegisterStatus;
  /** What is actually there. */
  built: string;
  /** What produced it — a method, a pack, a dataset. */
  producedBy: string;
  /** Where its data lives, if anywhere. */
  dataLocation: string;
  /** What backs the claim, or what is missing from it. */
  evidence: string;
}

