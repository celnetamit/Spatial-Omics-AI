/**
 * The result labels of §1.5, and the confidence categories of §5.1.
 *
 * These are not cosmetic. §1.4 puts "LLM-generated numerical biology" out of
 * scope and §13 forbids the model from inventing a number, so every value that
 * reaches a screen has to carry how it came to exist. A label travels with the
 * value from the function that produced it, rather than being attached by the
 * component that draws it — a badge decided at render time is a badge that can
 * be wrong.
 */

export type ResultLabel =
  /** Directly present in the input data. */
  | 'OBSERVED'
  /** Calculated by a defined analysis method. */
  | 'COMPUTED'
  /** Generated by a simulation or predictive model. */
  | 'PREDICTED'
  /** AI-assisted explanation of structured results. */
  | 'INTERPRETED'
  /** A testable interpretation, not an established fact. */
  | 'HYPOTHESIS'
  /** A recommended wet-lab or benchmark step. */
  | 'VALIDATION';

export const RESULT_LABEL_MEANING: Record<ResultLabel, string> = {
  OBSERVED: 'Directly present in the input data.',
  COMPUTED: 'Calculated by a defined analysis method.',
  PREDICTED: 'Generated by a simulation or predictive model.',
  INTERPRETED: 'AI-assisted explanation of structured results.',
  HYPOTHESIS: 'A testable interpretation, not an established fact.',
  VALIDATION: 'A recommended wet-lab or benchmark step.',
};

/**
 * §5.1 confidence, which is a statement about evidence rather than a number.
 *
 * `not-interpretable` is a first-class outcome and not a failure: §15.2(14)
 * requires the lab to be able to say a result cannot be interpreted, and a
 * system that can only ever return a confident answer has no way to.
 */
export type Confidence = 'high' | 'moderate' | 'exploratory' | 'not-interpretable';

export const CONFIDENCE_ORDER: Confidence[] = ['high', 'moderate', 'exploratory', 'not-interpretable'];

/** The weaker of two confidences — evidence does not improve by being combined. */
export function weakestConfidence(...values: Confidence[]): Confidence {
  let worst: Confidence = 'high';
  for (const value of values) {
    if (CONFIDENCE_ORDER.indexOf(value) > CONFIDENCE_ORDER.indexOf(worst)) worst = value;
  }
  return worst;
}

/** §8.1 evidence hierarchy. */
export type EvidenceClass =
  /** Same species, tissue and cell context, same perturbation, dose and time. */
  | 'direct-matched-experimental'
  /** Same mechanism, closely related context. Carries a transfer warning. */
  | 'near-context-experimental'
  /** A curated database record: identity and mechanism, not an effect size. */
  | 'curated-database'
  /** The output of a validated predictive model, with version and uncertainty. */
  | 'model-derived'
  /** A user-defined value with no qualified quantitative evidence. */
  | 'exploratory-scenario';

export const EVIDENCE_CLASS_USE: Record<EvidenceClass, string> = {
  'direct-matched-experimental': 'Highest priority for quantitative parameterisation.',
  'near-context-experimental': 'May be used with an explicit transfer warning.',
  'curated-database':
    'Supports identity, mechanism and pathway eligibility; not automatically a quantitative effect size.',
  'model-derived': 'Must include model version and uncertainty.',
  'exploratory-scenario':
    'Allowed only when explicitly labelled exploratory, and never used for research-grade claims.',
};

/** The confidence ceiling an evidence class imposes on anything derived from it. */
export function confidenceCeiling(evidence: EvidenceClass): Confidence {
  switch (evidence) {
    case 'direct-matched-experimental':
      return 'high';
    case 'near-context-experimental':
      return 'moderate';
    case 'curated-database':
      return 'moderate';
    case 'model-derived':
      return 'moderate';
    case 'exploratory-scenario':
      return 'exploratory';
  }
}

/** A value that knows what kind of thing it is. */
export interface Labelled<T> {
  value: T;
  label: ResultLabel;
  /** How it was produced — a method id and version, or a model id. */
  method: string;
  confidence: Confidence;
  /** Evidence record ids backing it, where any exist. */
  evidence?: string[];
}

export function observed<T>(value: T, source: string): Labelled<T> {
  return { value, label: 'OBSERVED', method: source, confidence: 'high' };
}

export function computed<T>(value: T, method: string, confidence: Confidence = 'high'): Labelled<T> {
  return { value, label: 'COMPUTED', method, confidence };
}

export function predicted<T>(
  value: T,
  method: string,
  confidence: Confidence,
  evidence: string[] = [],
): Labelled<T> {
  return { value, label: 'PREDICTED', method, confidence, evidence };
}
